"""Make the dub lessons: the English videos, rendered once, that every language is
laid over as its own audio track (see tools/fit_dub.py).

  python tools/make_dub.py

For each English page lesson in ../course_video/src/lessons/<id>/ (read only), writes
src/dub/<id>/ with copies of its data (timings, content, quizzes, caption words) and
<Comp>Dub.tsx: the English component with English screen words, no captions, sound on,
and the narration taken from public/audio/<voice>/ (voice=null: music + effects only).
Then src/dub/index.tsx (one <Comp>DubVideo per lesson) and src/dub/lessons.json.
Re-run after the English lessons change.
"""
import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
EN = HERE.parent / "course_video"
DUB = HERE / "src/dub"

EXPORT = re.compile(
    r"export const (\w+): React\.FC<\{ captions\?: boolean \}> = \(\{ captions = true \}\) => \(\n"
    r"  <PageLesson data=\{DATA\} blocks=\{PLAN\.blocks\} text=\{TEXT\} captions=\{captions\}\n"
    r"    polish=\{\{ \.\.\.(\w+), sound: captions \}\} />\n\);\n")
DURATION = re.compile(r"export const (\w+_DURATION) = PLAN\.total;")


def dub_component(src, lid):
    s = src
    s = s.replace('from "../shared/', 'from "../../lessons/shared/').replace('from "../plan"', 'from "../../lessons/plan"')
    s = s.replace(f'from "../../captions/{lid}/words.json"', 'from "./words.json"')
    m = EXPORT.search(s)
    if not m:
        raise SystemExit(f"{lid}: export block not in the expected form")
    comp, polish = m.groups()
    s = s[:m.start()] + f"""// Dub version (made by tools/make_dub.py): English video, no captions, sound on;
// narration from public/audio/<voice>/, or none (music + effects) when voice is null.
export const {comp}Dub: React.FC<{{ voice?: string | null }}> = ({{ voice = null }}) => {{
  setUI("en");
  const blocks = voice ? PLAN.blocks : PLAN.blocks.map((b) => ({{ ...b, clips: [] }}));
  return (
    <PageLesson data={{{{ ...DATA, id: voice ?? DATA.id }}}} blocks={{blocks}} text={{TEXT}} captions={{false}}
      polish={{{{ ...{polish}, sound: true }}}} />
  );
}};
""" + s[m.end():]
    s = s.replace('import { fps } from "../../theme";',
                  'import { fps } from "../../theme";\nimport { setUI } from "../../ui";', 1)
    return comp, DURATION.search(s).group(1), s


def main():
    lessons = {}
    for d in sorted(p for p in (EN / "src/lessons").iterdir() if p.is_dir() and p.name not in ("shared", "full")):
        main_tsx = [f for f in d.glob("*.tsx") if EXPORT.search(f.read_text(encoding="utf-8"))]
        if len(main_tsx) != 1:
            print(f"skip {d.name}: {len(main_tsx)} lesson components")
            continue
        lid, f = d.name, main_tsx[0]
        out = DUB / lid
        out.mkdir(parents=True, exist_ok=True)
        for j in ("timings.json", "content.json", "quizzes.json"):
            shutil.copy2(d / j, out / j)
        shutil.copy2(EN / f"src/captions/{lid}/words.json", out / "words.json")
        comp, dur, tsx = dub_component(f.read_text(encoding="utf-8"), lid)
        (out / f"{comp}Dub.tsx").write_text(tsx, encoding="utf-8")
        lessons[lid] = {"comp": comp, "duration": dur}

    imports = "\n".join(f'import {{ {v["comp"]}Dub, {v["duration"]} }} from "./{k}/{v["comp"]}Dub";'
                        for k, v in lessons.items())
    comps = "\n".join(
        f'    <Composition id="{v["comp"]}DubVideo" component={{{v["comp"]}Dub}} durationInFrames={{{v["duration"]}}}\n'
        f'      fps={{fps}} width={{width}} height={{height}} defaultProps={{{{ voice: null }}}} />'
        for v in lessons.values())
    (DUB / "index.tsx").write_text(f"""// Generated by tools/make_dub.py. Entry point for the dub videos, bundled apart from
// src/index.ts so the main lesson list (Root.tsx, npm run check) is untouched:
//   npx remotion bundle src/dub/index.tsx --out-dir=out/bundle_dub
// Each <Comp>DubVideo is the English video with music + effects and no voice.
import React from "react";
import {{ Composition, registerRoot }} from "remotion";
import {{ fps, width, height }} from "../theme";
{imports}

const DubRoot: React.FC = () => (
  <>
{comps}
  </>
);

registerRoot(DubRoot);
""", encoding="utf-8")
    (DUB / "lessons.json").write_text(json.dumps({k: v["comp"] for k, v in lessons.items()}, indent=1), encoding="utf-8")
    print(f"{len(lessons)} dub lessons: {' '.join(v['comp'] for v in lessons.values())}")


if __name__ == "__main__":
    main()
